import cron from 'node-cron';
import { Role } from '@prisma/client';
import { Router } from 'express';
import { prisma } from '../config/db.js';
import { env } from '../config/env.js';
import { authMiddleware } from '../middleware/auth.js';
import { requireRole } from '../middleware/requireRole.js';
import { generateInvoice } from '../modules/invoices/invoices.service.js';

export interface BillingRunResult {
  attempted: number;
  generated: number;
  closed: number;
  failures: Array<{ subscriptionId: string; message: string }>;
  durationMs: number;
}

const MAX_CATCH_UP_CYCLES = 12;

/**
 * Bills every ACTIVE, unpaused subscription whose cursor is due. Each subscription is
 * isolated in its own try/catch so one failure never stops the batch, and each period
 * is generated by the idempotent `generateInvoice`, so re-running is always safe.
 */
export async function runBilling(today = new Date()): Promise<BillingRunResult> {
  const started = Date.now();
  const due = await prisma.subscription.findMany({
    where: { status: 'ACTIVE', pausedAt: null, nextInvoiceDate: { lte: today } },
    select: { id: true },
    orderBy: { id: 'asc' },
  });
  const result: BillingRunResult = { attempted: due.length, generated: 0, closed: 0, failures: [], durationMs: 0 };
  for (const subscription of due) {
    try {
      for (let cycle = 0; cycle < MAX_CATCH_UP_CYCLES; cycle += 1) {
        const current = await prisma.subscription.findUnique({ where: { id: subscription.id }, select: { nextInvoiceDate: true, status: true, pausedAt: true } });
        if (!current?.nextInvoiceDate || current.nextInvoiceDate > today || current.status !== 'ACTIVE' || current.pausedAt) break;
        const outcome = await generateInvoice(subscription.id, undefined, today);
        if (outcome.status === 'created') result.generated += 1;
        if (outcome.status === 'closed') {
          result.closed += 1;
          break;
        }
      }
    } catch (error) {
      result.failures.push({ subscriptionId: subscription.id, message: error instanceof Error ? error.message : 'Unknown billing error' });
    }
  }
  result.durationMs = Date.now() - started;
  return result;
}

export function startBillingScheduler() {
  if (!cron.validate(env.BILLING_CRON)) throw new Error('BILLING_CRON is invalid');
  return cron.schedule(env.BILLING_CRON, () => { void runBilling().catch((error) => console.error('Billing job failed', error)); });
}

export const adminBillingRouter = Router();
adminBillingRouter.post('/run-billing', authMiddleware, requireRole(Role.ADMIN), async (_req, res, next) => {
  try { res.json(await runBilling()); } catch (error) { next(error); }
});
